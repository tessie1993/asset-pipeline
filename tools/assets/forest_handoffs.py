def render_index(entries: list[dict]) -> str:
    """The README listing every brief with the state of its sheet and build."""
    lines = [
        "# Forest asset build briefs", "",
        "Generated by `tools/assets/forest_handoffs.py` (state as of the last run). One self-contained brief per asset: "
        "hand a brief to a builder model as its whole task. Start with the master brief, "
        "`design/levels/forest/HANDOFF.md`, for the pipeline and how to spawn a builder.", "",
        "| # | Category | Canva name | Asset | Size x / y / z (m) | Budget | Canva sheet | Build | Brief |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for entry in entries:
        size = entry["size_m"]
        lines.append(f"| {entry['canva_id']} | {entry['category']} | {cell(entry['name'])} | `{entry['asset']}` | "
                     f"{size['x']} / {size['y']} / {size['z']} | {entry['triangle_budget']:,} | {entry['sheet']} | "
                     f"{entry['build']} | [{entry['file']}]({entry['file']}) |")
    lines += ["", f"{len(entries)} briefs."]
    return "\n".join(lines) + "\n"


def main() -> int:
    manifest = load_json(MANIFEST)
    specs = load_json(SPECS)["specs"]
    palette = load_json(PALETTE)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    entries = []
    for obj in manifest["objects"]:
        if not obj["asset"] or obj["status"] == SKIPPED:
            continue
        brief = f"{obj['canva_id']:02d}_{obj['asset']}.md"
        (OUT_DIR / brief).write_text(render_brief(obj, specs, palette, manifest["sheets"]), encoding="utf-8")
        fields = normalise(*build_source(obj["asset"], specs))
        entries.append({
            "canva_id": obj["canva_id"], "category": obj["category"], "name": obj["name"], "asset": obj["asset"],
            "size_m": fields["size_m"], "triangle_budget": fields["triangle_budget"],
            "sheet": "ready" if canva_sheet_path(obj).exists() else "missing", "build": build_state(obj["asset"]),
            "file": brief,
        })
    (OUT_DIR / "README.md").write_text(render_index(entries), encoding="utf-8")
    print(f"wrote {len(entries)} briefs and README.md to {rel(OUT_DIR)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
