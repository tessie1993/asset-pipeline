        "### `_shared.py` helpers (import as `S`)", "", SHARED_API, "",
        "### Rules", "", RULES.replace("<asset>", asset), "",
        "## 6. Acceptance checklist", "", CHECKLIST.replace("<asset>", asset), "",
        "## 7. Report format", "", REPORT_FORMAT, "",
