def slug(text: str) -> str:
    """Lower-case ``text`` with every run of non-alphanumerics turned into one underscore."""
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def cell(text: object) -> str:
    """``text`` made safe for a Markdown table cell."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def rel(path: Path) -> str:
    """``path`` relative to the repository, with forward slashes."""
    return path.relative_to(REPO_ROOT).as_posix()


def load_json(path: Path) -> dict:
    """The JSON document at ``path``."""
    return json.loads(path.read_text(encoding="utf-8"))


def identification_sheet(canva_id: int, sheets: list[dict]) -> Path:
    """The identification sheet listing object ``canva_id``; ``sheets`` are the manifest entries such as ``{"objects": "1-22"}``."""
    for sheet in sheets:
        first, last = (int(n) for n in sheet["objects"].split("-"))
        if first <= canva_id <= last:
            return REPO_ROOT / sheet["file"]
    raise SystemExit(f"no identification sheet lists Canva object {canva_id}")


def canva_sheet_path(obj: dict) -> Path:
    """Where the 360-degree sheet of ``obj`` is (or will be) saved."""
    if obj.get("turnaround"):
        return REPO_ROOT / obj["turnaround"]["image"]
    return CANVA_DIR / f"{obj['canva_id']:02d}_{slug(obj['name'])}_360.png"


def build_state(asset: str) -> str:
    """``built`` when a GLB exists, ``draft`` when only a generator does, else ``not started``."""
    if (MODELS_DIR / f"{asset}.glb").exists():
        return "built"
    if (GENERATORS_DIR / f"{asset}.py").exists():
        return "draft"
    return "not started"


def build_source(asset: str, specs: dict) -> tuple[str, dict]:
    """``("profile", data)`` when the asset has a profile, else ``("spec", data)``."""
    profile_path = PROFILES_DIR / f"forest_{asset}.json"
    if profile_path.exists():
        return "profile", load_json(profile_path)
    return "spec", specs[asset]


def normalise(source: str, data: dict) -> dict:
    """The fields the brief prints, from a profile or a spec."""
    if source == "profile":
        return {
            "kind": data["kind"], "size_m": data["size_m"], "size_note": data.get("size_note"), "origin": data["origin"],
            "triangle_budget": data["triangle_budget"], "materials": data["materials"],
            "collision": data["godot"]["collision"], "markers": data["godot"]["markers"],
            "depends_on": [], "extends": None, "build_notes": None,
        }
    return {
        "kind": data["kind"], "size_m": data["size_m"], "size_note": None, "origin": data["origin"],
        "triangle_budget": data["triangle_budget"], "materials": data["materials"],
        "collision": data["collision"], "markers": data["markers"],
        "depends_on": data["depends_on"], "extends": data["extends"], "build_notes": data["build_notes"],
    }


def state_line(asset: str, state: str) -> str:
    """One sentence telling the builder whether work already exists."""
    generator = f"`{rel(GENERATORS_DIR / f'{asset}.py')}`"
    if state == "built":
        return (f"A first build exists (`{rel(MODELS_DIR / f'{asset}.glb')}`, generator {generator}). "
                "Do not start over: review it against the references below, find what is wrong, and refine the generator.")
    if state == "draft":
        return (f"An unfinished generator exists ({generator}) but no GLB. Read it, keep what is right, "
                "finish or rewrite it.")
    return "Nothing exists yet for this asset."


def references_section(obj: dict, source: str, data: dict, sheets: list[dict]) -> list[str]:
    """Section 3: every reference image with its path and whether the file exists."""
    asset = obj["asset"]
    sheet = canva_sheet_path(obj)
    views = VIEWS_DIR / asset
    ident = identification_sheet(obj["canva_id"], sheets)
    rows = [
        ("Canva 360-degree sheet with caption", sheet, "exists" if sheet.exists() else "NOT GENERATED YET (see below)"),
        ("Canva sheet cut into views", views, "exists" if views.exists() else "not cut yet"),
        ("Whole mockup (the art style and the truth)", MOCKUP, "exists"),
        (f"Canva identification sheet holding object {obj['canva_id']}", ident, "exists"),
    ]
    lines = ["| Reference | Path | State |", "|---|---|---|"]
    lines += [f"| {cell(name)} | `{rel(path)}` | {state} |" for name, path, state in rows]
    if source == "profile":
        sprite = data["sprite"]
        sprite_png = SPRITES_DIR / f"{asset}.png"
        lines.append(f"| Mockup crop (sprite) | `{rel(sprite_png)}` | {'exists' if sprite_png.exists() else 'missing'} |")
        lines += ["", f"The sprite is the box `{sprite['crop']}` (x0, y0, x1, y1 pixels) of the 1200 x 896 mockup. "
                  f"It shows: {sprite['shows']}.", "",
                  f"Where to find it in the whole mockup: {data['where_in_image']}."]
        for extra in data.get("sprite_extra", []):
            lines.append(f"* Further crop `{extra['name']}` {extra['crop']}: {extra['shows']}.")
    else:
        lines += ["", "This object has no sprite crop. Find it in the whole mockup and on the identification sheet "
                  f"(object {obj['canva_id']}). Hint from the checks made so far: {obj['mockup_note']}"]
    lines += ["", CANVA_SHEET_HELP.replace("<asset>", asset), ""]
    if not sheet.exists():
        lines += [
            "**The Canva sheet has not been generated for this object yet.** The orchestrator makes it with the Canva tool "
            "(subagents have no Canva access). Build from the description, the numbers, the mockup and the identification "
            "sheet, say in your report that no sheet was available, and expect a follow-up pass against the sheet once it exists.",
            "",
        ]
    return lines


def spec_section(asset: str, source: str, data: dict, fields: dict) -> list[str]:
    """Section 4: the numbers and the description."""
    size = fields["size_m"]
    origin_of_numbers = f"`assets/data/forest/profiles/forest_{asset}.json`" if source == "profile" else \
        f"`assets/data/forest/forest_asset_specs.json`, key `{asset}`"
    lines = [
        f"Numbers come from {origin_of_numbers}; read it too. Sizes are estimates scaled to a 1.7 m trainer (Blender axes: x width, y depth, z height).",
        "",
        "| Field | Value |", "|---|---|",
        f"| Kind | {fields['kind']} |",
        f"| Size x / y / z | {size['x']} / {size['y']} / {size['z']} m |",
        f"| Origin and facing | {cell(fields['origin'])} |",
        f"| Triangle budget | {fields['triangle_budget']:,} render triangles |",
        f"| Materials | {', '.join(f'`{m}`' for m in fields['materials'])} |",
        f"| Collision | {cell(fields['collision'])} |",
        f"| Markers | {cell('; '.join(fields['markers'])) if fields['markers'] else 'none'} |",
        f"| Output | `{rel(MODELS_DIR / f'{asset}.glb')}` |",
    ]
    if fields["size_note"]:
        lines += ["", f"Size note: {fields['size_note']}"]
    if fields["extends"]:
        lines += ["", f"**Extends a finished asset:** `{fields['extends']}` (read it first)."]
    if fields["depends_on"]:
        parts = ", ".join(f"`{rel(MODELS_DIR / f'{part}.glb')}` ({'exists' if (MODELS_DIR / f'{part}.glb').exists() else 'NOT BUILT YET'})"
                          for part in fields["depends_on"])
        lines += ["", f"**Depends on finished parts:** {parts}. If a part's GLB does not exist, stop and report which one."]
    if source == "profile":
        lines += ["", "### Description", "", data["description"], "", "### Look (each line says what it is based on)", "",
                  "| Feature | Basis |", "|---|---|"]
        lines += [f"| {cell(item['feature'])} | {cell(item['basis'])} |" for item in data["look"]]
        lines += ["", "**Not visible in the sprite** (build these as the `Proposal` lines say and report them): "
                  + "; ".join(data["not_in_sprite"]) + ".", "",
                  f"**What the Canva sheet must show / what belongs to the object:** {data['turnaround_focus']}."]
    else:
        lines += ["", "### Build notes", "", fields["build_notes"]]
    return lines


def palette_section(materials: list[str], palette: dict) -> list[str]:
    """Section 5's palette table for the slots the asset uses."""
    lines = ["| Slot | base | lit | shadow | roughness | Used for |", "|---|---|---|---|---|---|"]
    for slot in materials:
        entry = palette["slots"].get(slot)
        if entry is None:
            lines.append(f"| `{slot}` | helper material | | | | see the `S.` helper in the API table |")
            continue
        lines.append(f"| `{slot}` | {entry['base']} | {entry.get('lit', '')} | {entry.get('shadow', '')} | "
                     f"{entry['roughness']} | {cell(entry['use'])} |")
    return lines


