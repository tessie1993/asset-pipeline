SHARED_API = """\
| Call | Use |
|---|---|
| `S.material(slot)`, `S.assign(obj, slot)` | Palette material for an `MF_*` slot; one material per slot per asset. |
| `S.mesh_from_bmesh(name, bm, slot=None)` | Bmesh to a linked mesh object; frees the bmesh. |
| `S.new_empty(name, location)` | Marker empty. Names: `attach_*`, `place_*`, `anchor_*`, `interact_*`, `water_<n>`. |
| `S.shade_smooth_by_angle(obj, degrees)` | Smooth shading with crisp edges beyond an angle. |
| `S.ground_tile_material()`, `S.set_vertex_colors(obj, srgb_per_vertex)` | Vertex-coloured ground (`MF_GroundTile`): one sRGB colour per vertex, exported as `COLOR_0`. |
| `S.light_shaft_material(alpha, strength)` | The emissive, alpha-blended `MF_LightShaft` material. |
| `S.load_profile(name)`, `S.report(profile)`, `S.render_views(dir, name)` | Used by `run`; call them directly only if you need to. |
| `S.run(name, build)` | Standard `main`. Fails if the triangle budget is exceeded, a material is not an allowed slot, a mesh has no material or an unapplied transform. A size outside +-35 % of the estimate is only a warning. Flags after `--`: `--draft` (do not write the GLB), `--preview DIR` (render eight views), `--out DIR`. |"""

RULES = """\
* **Deterministic.** Fixed random seeds; the same script gives the same GLB.
* **Units and axes.** 1 unit = 1 m, Z up, the front faces Blender -Y (Godot +Z). Put the origin where the spec says. Apply all transforms.
* **Materials.** Only the `MF_*` slots (and `MF_GroundTile` / `MF_LightShaft` via the helpers). Never type a colour by hand. Merge static meshes that share a material.
* **Geometry, not cards.** Thin crisp features (rope, leaf edges, planks) are real geometry, not alpha cards, so the toon shader works and the web build stays simple. The only alpha material is `MF_LightShaft`.
* **Silhouette first.** If you are debating detail against silhouette, choose silhouette. Chunky, slightly irregular, hand-made proportions match the mockup; do not make it neat.
* **Triangle budget.** Render triangles only; collision proxies do not count. Stay under the budget in section 4.
* **Collision.** A simple proxy mesh named `<asset>-colonly` (trimesh) or `<asset>-convcolonly` (convex hull) becomes Godot collision. Proxies are excluded from the budget and from the preview.
* **Markers.** Empties named as the spec says, at the positions the spec says.
* **Files you may write:** `tools/blender/forest/<asset>.py`, `assets/models/forest/<asset>.glb` (and the `.glb.import` Godot creates), `production/qa/evidence/forest/<asset>_review.png`. **Do not edit** `_shared.py`, `palette.py`, `review_sheet.py`, `tools/blender/common/`, any other asset's script, or any data file. If the pipeline blocks you, stop and report exactly what is missing.
* **Do not** call Canva, do not use Meshy or any image-to-3D service, do not run `git commit` or `git push` (the orchestrator does). Do not delete files by variable path: use a new scratch folder per iteration.
* **Interruptions.** A user interruption stops you without warning and loses everything not on disk. Write the generator file early and keep it runnable after every edit."""

