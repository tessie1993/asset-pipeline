        f"{state_line(asset, build_state(asset))}", "",
        "## 2. What Canva says this object is", "",
        f"* **Canva name:** {obj['name']}",
        f"* **Canva description (verbatim):** {obj['canva_description']}",
        f"* **Description Canva wrote under its 360-degree sheet (verbatim):** {caption if caption else 'not generated yet'}",
        f"* **Checked against the mockup:** `{obj['mockup_check']}`. {obj['mockup_note']}", "",
        "How to weigh the sources:", "", SOURCE_OF_TRUTH, "",
        "## 3. Reference images", "", "Open every existing image with the Read tool before you model.", "",
        *references_section(obj, source, data, sheets),
        "## 4. What to build", "",
        *spec_section(asset, source, data, fields), "",
        "## 5. How to build it", "",
        "1. Read this whole brief and look at every reference image in section 3.",
        "2. Read one finished sibling generator for the house style: `tools/blender/forest/rope_bridge.py` (structure) "
